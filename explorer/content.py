def fmt_num(x: float | None, digits: int = 1) -> str:
    if x is None or x != x:  # None or NaN
        return "n/a"
    return f"{x:,.{digits}f}"


def rule_sentence(row: dict) -> str:
    """Plain-language statement of how a rule evaluated for a state (used by app and site)."""
    metric = METRIC_LABELS.get(row["metric"], row["metric"])
    comp = COMPARATOR_LABELS.get(row["comparator"], row["comparator"])
    window = f"{int(row['window_start'])}-{int(row['window_end'])}"
    digits = 1 if row["metric"] == "median_minutes" else 2
    if not row["evaluable"]:
        return (
            f"{row['label']} ({window}): not evaluated - only {int(row['n'] or 0)} usable records "
            f"(rule needs at least {int(row['min_n'])})."
        )
    rel = "above" if row["value"] > row["comparator_value"] else "at or below"
    return (
        f"{row['label']} ({window}): {fmt_num(row['value'], digits)} {metric}, {rel} "
        f"{comp} ({fmt_num(row['comparator_value'], digits)})."
    )
